'use strict';
/*
  Builds ready-to-open Arduino sketch folders for both Heltec boards:

    ../firmware/heltec1_pi_bridge/   heltec1_pi_bridge.ino  mesh_protocol.h
    ../firmware/heltec2_field_node/  heltec2_field_node.ino mesh_protocol.h node_assets.h node_cert.h partitions.csv node-map.amp

  Sources (edit these, then run this again):
    ../heltec1-pi-bridge.c, ../heltec2-remote-node.c, ../mesh_protocol.h   firmware
    ../heltec-node.html                                                    the field app (GPS gate is put in here)
    tools/client/*.js, map-service.js                                      map engine for the field app (/amp-map.js)
    app/vendor/leaflet.js                                                  Leaflet 1.9.4

      node tools/build-firmware.js
*/
const fs = require('fs'), path = require('path'), zlib = require('zlib'), cp = require('child_process');
const PC = path.join(__dirname, '..');                       // pi-command-center
const ROOT = path.join(PC, '..');                            // website
const FW = path.join(ROOT, 'firmware');
const N1 = path.join(FW, 'heltec1_pi_bridge'), N2 = path.join(FW, 'heltec2_field_node');
const WWW = path.join(PC, 'test', '.node-www');              // plain copies for the node simulator (test/node-sim.js)
for (const d of [N1, N2, WWW]) fs.mkdirSync(d, { recursive: true });
const LF = String.fromCharCode(10), CR = String.fromCharCode(13);
const read = (p) => fs.readFileSync(p, 'utf8');

// ------------------------------------------------------------------ 1. field app page (+ GPS gate)
const htmlFile = path.join(ROOT, 'heltec-node.html');
let html = read(htmlFile);
const gate = read(path.join(__dirname, 'client', 'gps-gate.js')).split(CR + LF).join(LF);
const OPEN = '<!--AMP-GATE-->', CLOSE = '<!--/AMP-GATE-->';
const cfg = { requireGps: true, https: true, httpsPort: 443, insecureSkip: false, exemptLocal: false };
const block = OPEN + LF + '<script>window.AMP_CFG=' + JSON.stringify(cfg) + ';</script>' + LF + '<script>' + LF + gate + LF + '</' + 'script>' + LF + CLOSE + LF;
const a = html.indexOf(OPEN), b = html.indexOf(CLOSE);
if (a >= 0 && b > a) html = html.slice(0, a) + block + html.slice(b + CLOSE.length + 1);
else {
  const anchor = '<div id="toast"></div>' + LF;
  if (html.split(anchor).length !== 2) throw new Error('anchor <div id="toast"> not found once');
  html = html.replace(anchor, () => anchor + LF + block);
}
const marker = '/*AMP-GPS-PREFER*/';
if (!html.includes(marker)) {
  const from = "var fallback = { lat: (currentUser && currentUser.lat) || BASE_LAT, lon: (currentUser && currentUser.lon) || BASE_LON };";
  if (html.split(from).length !== 2) throw new Error('getLocation anchor not found once');
  html = html.replace(from, () => from + LF + '    ' + marker + ' if (window.AMP_GPS && Date.now() - window.AMP_GPS.ts < 45000) { resolve({ lat: window.AMP_GPS.lat, lon: window.AMP_GPS.lng }); return; }');
}
fs.writeFileSync(htmlFile, html);

// ------------------------------------------------------------------ 2. map engine bundle (/amp-map.js) + Leaflet
const glue = (title, list) => '/* AMPING field node: ' + title + ' - generated by tools/build-firmware.js from: ' + list.join(', ') + ' */' + LF +
  list.map(p => '/* ---- ' + p + ' ---- */' + LF + read(path.join(PC, p)).split(CR + LF).join(LF) + LF + ';').join(LF);
// light page (/lite): map engine + its own map screen + the shared map / live-position code
const parts = ['map-service.js', 'tools/client/node-bundle.js', 'tools/client/node-map-source.js', 'tools/client/node-map.js', 'tools/client/offline-map.js', 'tools/client/live-units.js'];
const ampMap = glue('light page map engine (/amp-map.js)', parts);
// full app (/): loaded before the app's own scripts - map file in the phone + one-request sync
const nodeParts = ['map-service.js', 'tools/client/node-bundle.js', 'tools/client/node-map-source.js', 'tools/client/node-app-bridge.js'];
const ampNode = glue('full app support (/amp-node.js)', nodeParts);

// ------------------------------------------------------------------ 2b. the FULL command-center app, node edition (served at /)
// Same page as on the Pi (app/index.html, already patched by patch-app.js) with:
//   no Firebase library (the app's own offline stand-ins take over - nothing ever talks to Firebase),
//   logos from the node, GPS gate in https mode, the node's map file, and one-request sync.
function nodeEdition(src) {
  let h = src.split(CR + LF).join(LF);
  const swap = (name, re, to, expect) => {
    const n = (h.match(re) || []).length;
    if (expect !== undefined && n !== expect) throw new Error('node edition: "' + name + '" expected ' + expect + ' match(es), found ' + n);
    h = h.replace(re, to);
  };
  swap('firebase sdk', /[ \t]*<script src="https:\/\/www\.gstatic\.com\/firebasejs\/[^"]+"><\/script>\n?/g, '', 6);
  // The logos travel inside the page (firmware 2026-10-31a). They used to be two more requests, and the node keeps
  // only three secure connections for ALL phones together: a page that wanted three at once took the whole server,
  // and the next phone's page was cut off halfway. Gzip folds the repeated copies back down.
  swap('logos', /https:\/\/tech2forms\.com\/wp-content\/uploads\/2026\/08\/([A-Za-z0-9_.-]+\.png)/g,
    (m, f) => logoData[f] || ('/vendor/img/' + f));
  swap('ollama', /http:\/\/127\.0\.0\.1:11434\/api\/generate/g, '/api/generate');
  swap('sync pull', /const pull = \(api, file\) => fetch\(api \+ cb[^\n]*\n[^\n]*\n/g, "const pull = (api, file) => window.ampNodePull(api); /*AMPING-NODE: one request per sync*/\n", 1);
  swap('infra pull', /const pInfra = fetch\('\/api\/infra' \+ cb[^\n]*/g, "const pInfra = window.ampNodePull('/api/infra'); /*AMPING-NODE*/", 1);
  // ONE request for the whole page (firmware 2026-10-29b): the field node keeps only 3 secure connections, and a
  // page that also pulled /leaflet.js and /amp-node.js needed three at once - a second phone opening the app pushed
  // the first phone's connection out, and its app fell back to "disconnected". The separate routes stay (light page).
  const inlineScript = (code, what) => {
    if (code.indexOf('</' + 'script') >= 0) throw new Error('cannot inline ' + what + ': it contains a closing script tag');
    return '<script>' + LF + code + LF + '</' + 'script>';
  };
  swap('map support', /<script id="amping-offline-map">(?=\n)/g, () => inlineScript(ampNode, '/amp-node.js') + LF + '<script id="amping-offline-map">', 1);
  swap('leaflet inline', /[ 	]*<script src="\/leaflet\.js"><\/script>/g, () => inlineScript(leafletJs, '/leaflet.js'), 1);
  // One request per phone (firmware 2026-10-31a): the queue goes in above reliable-send.js so the outbox's retries
  // are queued too, and an empty icon link stops the browser asking for /favicon.ico (which the node answers with a
  // redirect to the app page - a second 256 KB download for nothing).
  const oneConn = read(path.join(__dirname, 'client', 'node-one-connection.js')).split(CR + LF).join(LF);
  swap('one connection', /<script id="amping-reliable-send">/, () => inlineScript(oneConn, 'node-one-connection.js') + LF + '<script id="amping-reliable-send">', 1);
  const cfg = { requireGps: true, https: true, httpsPort: 443, insecureSkip: false, exemptLocal: false };
  swap('head', /<head>/i, () => '<head><link rel="icon" href="data:,"><script>window.AMP_CFG=' + JSON.stringify(cfg) + ';window.AMP_NODE=true;</script>');
  if (/firebasejs|gstatic\.com|tech2forms\.com/.test(h)) throw new Error('node edition still references the internet');
  return h;
}
const logos = fs.readdirSync(path.join(__dirname, 'node-img')).filter(f => f.endsWith('.png'));
// the same logos as data: URIs, so the node edition of the app carries them instead of asking for them
const logoData = logos.reduce((m, f) => (m[f] = 'data:image/png;base64,' + fs.readFileSync(path.join(__dirname, 'node-img', f)).toString('base64'), m), {});
const leafletJs = read(path.join(PC, 'app', 'vendor', 'leaflet.js'));
const cssFile = path.join(PC, 'app', 'vendor', 'leaflet.css');
if (!fs.existsSync(cssFile)) {
  // the command-center app carries Leaflet's stylesheet inline - reuse it
  const app = read(path.join(ROOT, 'raspberrypi-index final.html'));
  const line = app.split(LF).map(l => l.trim()).find(l => l.startsWith('.leaflet-pane,.leaflet-tile'));
  if (!line) throw new Error('Leaflet CSS not found in raspberrypi-index final.html');
  fs.writeFileSync(cssFile, line + LF);
}
const leafletCss = read(cssFile);
const appSrc = path.join(PC, 'app', 'index.html');
const nodeApp = nodeEdition(read(appSrc));

// ------------------------------------------------------------------ 3. syntax check of everything that runs in the phone
let bad = 0;
const check = (name, code) => { try { new Function(code); } catch (e) { bad++; console.error('script error in ' + name + ': ' + e.message); } };
const re = /<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g; let m, k = 0;
while ((m = re.exec(html))) { k++; if (m[1].trim()) check('heltec-node.html script #' + k, m[1]); }
check('amp-map.js', ampMap);
check('amp-node.js', ampNode);
const re2 = /<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g; k = 0;
while ((m = re2.exec(nodeApp))) { k++; if (m[1].trim()) check('node edition app script #' + k, m[1]); }
if (bad) process.exit(1);

// ------------------------------------------------------------------ 4. node_assets.h (gzip, served straight from flash)
const assets = [['NODE_APP_GZ', nodeApp], ['NODE_PAGE_GZ', html], ['LEAFLET_JS_GZ', leafletJs], ['LEAFLET_CSS_GZ', leafletCss], ['AMP_MAP_JS_GZ', ampMap], ['AMP_NODE_JS_GZ', ampNode]];
let out = '// Generated by pi-command-center/tools/build-firmware.js - do not edit, run the tool again.' + LF + '#pragma once' + LF + '#include <stdint.h>' + LF + LF;
const sizes = [];
for (const [name, text] of assets) {
  const gz = zlib.gzipSync(Buffer.from(text, 'utf8'), { level: 9 });
  sizes.push(name + ' ' + (gz.length / 1024).toFixed(1) + ' KB');
  out += 'static const uint8_t ' + name + '[] = {' + LF;
  for (let i = 0; i < gz.length; i += 24) out += '  ' + Array.from(gz.subarray(i, i + 24)).map(v => '0x' + v.toString(16).padStart(2, '0')).join(',') + ',' + LF;
  out += '};' + LF + LF;
}
// logos (already small PNGs, served as they are): /vendor/img/<name>
out += 'struct NodeLogo { const char* path; const uint8_t* data; size_t len; };' + LF;
logos.forEach((f, i) => {
  const b = fs.readFileSync(path.join(__dirname, 'node-img', f));
  sizes.push('logo' + (i + 1) + ' ' + (b.length / 1024).toFixed(1) + ' KB');
  out += 'static const uint8_t NODE_LOGO_' + i + '[] = {' + LF;
  for (let j = 0; j < b.length; j += 24) out += '  ' + Array.from(b.subarray(j, j + 24)).map(v => '0x' + v.toString(16).padStart(2, '0')).join(',') + ',' + LF;
  out += '};' + LF;
});
out += 'static const NodeLogo NODE_LOGOS[] = {' + LF + logos.map((f, i) => '  { "/vendor/img/' + f + '", NODE_LOGO_' + i + ', sizeof(NODE_LOGO_' + i + ') },').join(LF) + LF + '};' + LF;
out += 'static const int NODE_LOGO_COUNT = ' + logos.length + ';' + LF;
fs.writeFileSync(path.join(N2, 'node_assets.h'), out);
fs.writeFileSync(path.join(WWW, 'index.html'), html);
fs.writeFileSync(path.join(WWW, 'app.html'), nodeApp);
fs.writeFileSync(path.join(WWW, 'amp-node.js'), ampNode);
fs.mkdirSync(path.join(WWW, 'vendor', 'img'), { recursive: true });
for (const f of logos) fs.copyFileSync(path.join(__dirname, 'node-img', f), path.join(WWW, 'vendor', 'img', f));
fs.writeFileSync(path.join(WWW, 'amp-map.js'), ampMap);
fs.writeFileSync(path.join(WWW, 'leaflet.js'), leafletJs);
fs.writeFileSync(path.join(WWW, 'leaflet.css'), leafletCss);

// ------------------------------------------------------------------ 5. node_cert.h (self-signed, kept between builds so phones are asked only once)
const TLS = path.join(__dirname, 'node-tls');
const certPem = path.join(TLS, 'cert.pem'), keyPem = path.join(TLS, 'key.pem');
if (!fs.existsSync(certPem) || !fs.existsSync(keyPem)) {
  fs.mkdirSync(TLS, { recursive: true });
  console.log('creating the field node certificate (openssl) ...');
  cp.execFileSync('openssl', ['req', '-x509', '-newkey', 'ec', '-pkeyopt', 'ec_paramgen_curve:prime256v1', '-noenc',
    '-keyout', keyPem, '-out', certPem, '-subj', '/CN=AMPING Field Node/O=AMPING Mesh',
    '-addext', 'subjectAltName=IP:192.168.4.1', '-addext', 'basicConstraints=critical,CA:FALSE',
    '-addext', 'keyUsage=critical,digitalSignature', '-addext', 'extendedKeyUsage=serverAuth',
    '-not_before', '20260101000000Z', '-not_after', '20351231235959Z'], { stdio: 'inherit' });
}
const cLines = (pem) => pem.split(CR + LF).join(LF).trim().split(LF).map(l => '  "' + l + '\\n"').join(LF);
fs.writeFileSync(path.join(N2, 'node_cert.h'),
  '// Self-signed certificate for https://192.168.4.1 (from pi-command-center/tools/node-tls). Generated - do not edit.' + LF +
  '// Phones show a one-time "not private" warning for it; that is expected on this closed emergency network.' + LF +
  '#pragma once' + LF + 'static const char NODE_CERT_PEM[] =' + LF + cLines(read(certPem)) + ';' + LF +
  'static const char NODE_KEY_PEM[] =' + LF + cLines(read(keyPem)) + ';' + LF);

// ------------------------------------------------------------------ 6. sketch folders
const proto = read(path.join(ROOT, 'mesh_protocol.h'));
fs.writeFileSync(path.join(N1, 'heltec1_pi_bridge.ino'), read(path.join(ROOT, 'heltec1-pi-bridge.c')));
fs.writeFileSync(path.join(N1, 'mesh_protocol.h'), proto);
fs.writeFileSync(path.join(N2, 'heltec2_field_node.ino'), read(path.join(ROOT, 'heltec2-remote-node.c')));
fs.writeFileSync(path.join(N2, 'mesh_protocol.h'), proto);
fs.writeFileSync(path.join(N2, 'partitions.csv'), [
  '# AMPING field node flash layout: 3.2 MB program + 4.6 MB storage (map + optional page).',
  '# Picked up automatically by the Arduino IDE. Works on 8 MB and 16 MB flash boards.',
  '# Name,   Type, SubType,  Offset,   Size',
  'nvs,      data, nvs,      0x9000,   0x5000,',
  'otadata,  data, ota,      0xe000,   0x2000,',
  'app0,     app,  ota_0,    0x10000,  0x330000,',
  'spiffs,   data, spiffs,   0x340000, 0x4B0000,',
  'coredump, data, coredump, 0x7F0000, 0x10000,', ''].join(LF));
if (!fs.existsSync(path.join(N2, 'node-map.amp'))) cp.execFileSync(process.execPath, [path.join(__dirname, 'build-node-map.js')], { stdio: 'inherit' });

console.log('heltec-node.html ' + (html.length / 1024).toFixed(1) + ' KB; assets (gzip): ' + sizes.join(', '));
console.log('sketches ready: ' + N1 + LF + '                ' + N2);
